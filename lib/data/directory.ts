export function catBySlug(slug: string): DirCat | undefined {
  return DIR_CATS.find(c => c.slug === slug)
}

export function listingsByCat(slug: string): Listing[] {
  return LISTINGS.filter(l => l.cat === slug)
}

export function listingById(id: string): Listing | undefined {
  return LISTINGS.find(l => l.id === id)
}
